    public void load()
    {
        int a;
        try {
            pst = connection.prepareStatement("SELECT * FROM product");
            ResultSet rs = pst.executeQuery();
        
            ResultSetMetaData rd = rs.getMetaData();
            a = rd.getColumnCount();
            System.out.println("culomn number is "+ a);
            df = (DefaultTableModel)produitTable.getModel();
            df.setRowCount(0);
            
            while(rs.next())
            {
                Vector v2 = new Vector();
                for(int i=0; i<=a; i++)
                {
                    v2.add(rs.getString("idProduit"));
                    v2.add(rs.getString("pname"));
                    v2.add(rs.getString("description"));
                    v2.add(rs.getString("barcode"));
                    v2.add(rs.getString("prix_achat"));
                    v2.add(rs.getString("prix_vente"));
                    v2.add(rs.getString("quantite"));                       
                }
                df.addRow(v2);
            }
     
        } catch (SQLException ex) {
            Logger.getLogger(produits.class.getName()).log(Level.SEVERE, null, ex);
        }
    
    }


    private void modifierProdBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_modifierProdBtnActionPerformed
        df = (DefaultTableModel) produitTable.getModel();
        int selected = produitTable.getSelectedRow();

        int id = Integer.parseInt(df.getValueAt(selected, 0).toString());

        String pname = pnameTxt.getText();
        String des = desnameTxt.getText();
        String barcode = barcnameTxt.getText();
        String prix_achat  = prix_achatTxt.getText();
        String prix_vente  = prix_venteTxt.getText();
        String quantite  = quantiteTxt.getText();

        try {

            pst = connection.prepareStatement("UPDATE product set pname = ?, description =?, barcode =?, prix_achat=?, prix_vente=?, quantite=? where idProduit =?");
            pst.setString(1, pname);
            pst.setString(2, des);
            pst.setString(3, barcode);
            pst.setString(4, prix_achat);
            pst.setString(5, prix_vente);
            pst.setString(6, quantite);
            pst.setInt(7, id);

            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Produit updated");

            pnameTxt.setText("");
            desnameTxt.setText("");
            barcnameTxt.setText("");
            prix_achatTxt.setText("");
            prix_venteTxt.setText("");
            quantiteTxt.setText("");
            pnameTxt.requestFocus();
            load();
            produitTable.setEnabled(true);
        } catch (SQLException ex) {
            Logger.getLogger(produits.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_modifierProdBtnActionPerformed

